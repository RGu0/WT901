class Register(IntEnum):
    """寄存器地址。**每个成员的 docstring 都标了自己的出处**，因为出处逐项不同。

    ``0x7F`` 是唯一一个**两份上游资料都查不到**的地址，见
    :attr:`SERIAL_NUMBER`——它此前混在「已核实的寄存器地址」这句话里，看不出来。
    """

    SAVE = 0x00
    """写 0x0000 把当前配置固化到设备。"""

    CALSW = 0x01
    """校准控制，取值见 :class:`CalibrationMode`。"""

    RRATE = 0x03
    """回传速率，取值见 :class:`ReturnRate`。"""

    BANDWIDTH = 0x1F
    """抗混叠滤波器带宽，取值见 :class:`Bandwidth`。

    它**不改变样本速率**，只改变样本内容的频率成分——所以设错了，速率、丢包、连接
    这些可观测量全部正常，只有数据的频谱不对。
    """

    MOUNTING = 0x23
    """安装方向，取值见 :class:`Mounting`。

    **出处：协议文档有，官方 SDK 没有。** SDK 从不读也不写这个地址，所以这一条没有
    可参照的上游实现——本库的读写时序是照通用的「解锁—写—保存」套的。

    出厂默认是不是 :attr:`Mounting.HORIZONTAL`（0）**本库没有核实过**，所以显式写它
    可能是幂等的，也可能不是。两种情况下这一步都必须写：不写就等于依赖设备残留的
    配置，而模块会被别处用过、配置又固化在 flash。要让「一份配置快照完全决定设备
    状态」成立，这一步不能省。
    """

    ALGORITHM = 0x24
    """姿态解算算法，取值见 :class:`AlgorithmMode`。

    **出处：协议文档有，官方 SDK 没有。**

    它还门控着 ``CALSW`` 的一部分行为：手册对「Z 轴角度归零」
    （``FF AA 01 04 00``）注明**需先切到 6 轴算法才生效**。
    """

    READADDR = 0x27
    """读寄存器指令的操作码（不是一个可读写的数据寄存器）。"""

    VERSION_LOW = 0x2E
    VERSION_HIGH = 0x2F
    """两寄存器拼成 uint32 的固件版本号。"""

    CHIP_TIME_YEAR_MONTH = 0x30
    CHIP_TIME_DAY_HOUR = 0x31
    CHIP_TIME_MINUTE_SECOND = 0x32
    CHIP_TIME_MILLISECOND = 0x33
    """芯片时间，前三个寄存器的高低字节各承载一个字段。

    **出处：协议文档有，官方 SDK 没有。**
    """

    HX = 0x3A
    HY = 0x3B
    HZ = 0x3C
    """磁场三轴原始值，换算系数由 :attr:`MAGTYPE` 决定。"""

    TEMPERATURE = 0x40
    """温度原始值，除以 100 得摄氏度。"""

    Q0 = 0x51
    Q1 = 0x52
    Q2 = 0x53
    Q3 = 0x54
    """四元数，各除以 32768。"""

    POWER = 0x64
    """电池原始值（约等于电压 ×100）。"""

    MAC = 0x66
    """设备自报的蓝牙地址首寄存器，共 3 个寄存器 6 字节。

    **出处：协议文档有（作 ``MAC0``/``MAC1``/``MAC2``），官方 SDK 没有。** 协议文档
    因此背书了「跨 3 个寄存器」这件事，但**它没给字节序**——下面那条排布是本库自己
    用排除法定的，仍未被标签比对证实。

    **字节序是反的**：``0x66``–``0x68`` 按小端取出的 6 个字节，是蓝牙地址的
    **空口顺序**（低位在前），显示顺序要整体倒过来。取值与排布见
    :meth:`~wt901.telemetry.Telemetry.read_mac`。

    这是本库唯一可跨主机持久化的设备身份——:attr:`~wt901.discovery.DiscoveredDevice.address`
    在 macOS 上是 CoreBluetooth UUID，换台主机就变。
    """

    KEY = 0x69
    """写 :data:`UNLOCK_KEY` 解锁配置寄存器。"""

    MAGTYPE = 0x72
    """磁场量纲类型。磁场换算必须先读它，系数不是常量。

    **出处：官方 SDK 有（``DipSensorMagHelper.java`` 的分档换算），协议文档没有。**
    与本模块其余各项相反——这一条只有代码背书，没有文档背书。
    """

    SERIAL_NUMBER = 0x7F
    """序列号首寄存器，共 6 个寄存器 12 字节 ASCII。

    ⚠ **出处：协议文档没有，官方 SDK 也没有——两份上游资料都查不到这个地址。**
    它进本库时没有留下出处，2026-08-28 回头查两边都零命中（``ray-309``）。本模块
    只有这一条是这样。

    **而且它在真机上四台次全为零**（``ray-172`` 两台不同主机、``ray-279`` 两台不同
    设备）。此前的解释是「这批器件的序列号没烧写」；更简单的解释是**本型号根本没有
    这个寄存器，读一个未定义地址就返回零**。两种解释目前分不开，``ray-309`` scope 2
    读几个官方标为保留/未定义的地址与它比对来定论。

    在定论之前，:meth:`~wt901.telemetry.Telemetry.read_serial_number` 承诺的东西
    **可能是本型号没有的**。它如实报告「读到了但内容全零」这一点没错（``ray-293``
    的三态），错的是把「读得到」当成「这个寄存器存在」。
    """

    DISPLACEMENT_OUTPUT = 0x96
    """置 1 后 0x61 帧的负载语义改为位移/位移速度/角度。

    **出处：协议文档有，官方 SDK 没有。**
    """


UNLOCK_KEY = 0xB588
"""写入 :attr:`Register.KEY` 的解锁魔数。"""

REGISTERS_PER_RESPONSE = 8
"""一次读请求的回帧携带的寄存器个数——这是协议固定的，不是可选的。

**曾经写作 4，那是错的。** 2026-08-27 于 WT901BLE67 实测（``tools/probe_register_width.py``，
证据 ``ray-292/register-response-width/acceptance/``）：读 ``0x2E`` 的应答里，第 5、6 个
位置解出的分/秒与毫秒（``0x32``/``0x33``）夹在前后两次直读 ``0x30`` 的结果之间；读 ``0x3A``
的应答第 7 个位置（``0x40``）是 30.04 °C，与直读 ``0x40`` 的 30.03 °C 相符。两处都落在
原先被丢弃的那 8 个字节里，各测 3 轮全部成立。

帧长本来就算得出来：负载 18 字节 = 2 字节起始地址 + 16 字节寄存器区 = 8 个寄存器，
按 4 解会有 8 个字节没有说法。``decode_register_response`` 当时用 ``unpack_from`` 只取前
4 个，多出来的部分被静默丢弃，所以这个差异一直没暴露——**离线测试永远发现不了它**，
构造帧的测试工具与被测代码用的是同一个错误常量。
"""

MAG_START = Register.HX
QUATERNION_START = Register.Q0
MAC_START = Register.MAC
MAC_WORDS = 3
"""蓝牙地址占的寄存器个数。6 字节 ÷ 每寄存器 2 字节，一次读取就够。"""

SERIAL_NUMBER_START = Register.SERIAL_NUMBER
SERIAL_NUMBER_WORDS = 6


class AlgorithmMode(IntEnum):
    """写入 :attr:`Register.ALGORITHM` 的姿态解算算法。

    **编码与直觉相反**：值大的 ``1`` 对应的是「轴少」的那个。所以本库要求用具名
    成员而不是裸 0/1——写反了设备不会报错，只会让航向从相对航向变成依赖磁力计的
    绝对航向，在室内金属环境下悄悄劣化。这种错误在数据里看不出来。
    """

    NINE_AXIS = 0
    """9 轴：绝对航向，融合磁力计。磁环境干净时航向不随时间漂移。"""

    SIX_AXIS = 1
    """6 轴：相对航向，不用磁力计。航向会缓慢漂移，但不受磁干扰影响。

    「Z 轴角度归零」只在这个模式下生效。
    """


class Mounting(IntEnum):
    """写入 :attr:`Register.MOUNTING` 的安装方向。

    编码不像 :class:`AlgorithmMode` 那样反直觉（0 水平、1 垂直），但**写错同样不会
    报错**：装反了只是让姿态解算的重力轴对不上，数据一直偏，而链路、速率、丢包这些
    可观测量全部正常。所以仍然要求具名。
    """

    HORIZONTAL = 0
    """水平安装。适配文档 §3.1 要求的就是这一档。

    **它是不是出厂默认，本库没有核实过**——手册没写，也没人读过一台出厂状态设备的
    ``0x23``。正因为不确定，这次写入更不能省：见 :attr:`Register.MOUNTING`。
    """

    VERTICAL = 1
    """垂直安装。"""


class CalibrationMode(IntEnum):
    """写入 :attr:`Register.CALSW` 的校准模式。"""

    NORMAL = 0x0000
    """退出校准，恢复正常输出。也用于结束磁场校准。"""

    ACCELERATION = 0x0001
    """加计校准，要求设备水平静置。"""

    MAGNETIC_FIELD = 0x0007
    """开始磁场校准，需绕 XYZ 三轴各转一圈后写回 :attr:`NORMAL`。"""


class ReturnRate(IntEnum):
    """写入 :attr:`Register.RRATE` 的回传速率。

    **每一档都在真机上实测过。** 2026-08-18 于 WT901BLE67 逐档写入并测量实际样本
    速率，见 ``tools/probe_rates.py`` 与 evidence
    ``ray-171/register-access/acceptance/``：

    ======  ==========  ======
    编码    实测         偏差
    ======  ==========  ======
    0x06    10.05 Hz    0.5%
    0x07    19.86 Hz    0.7%
    0x08    49.45 Hz    1.1%
    0x09    99.26 Hz    0.7%
    0x0B    198.43 Hz   0.8%
    ======  ==========  ======

    **``0x0A`` 被有意排除。** 维特通用编码表标它为 125 Hz，但实测 99.29 Hz——与
    ``0x09`` 几乎相同。这不是链路带宽不足：同一次探测里 ``0x0B`` 跑到了 198 Hz。
    说明该固件并未按通用表映射这个编码。测不准的不进枚举。

    低于 10 Hz 的档位（0x01–0x05）未探测，需要时按同样方式实测后再加。
    """

    HZ_10 = 0x06
    """出厂默认值。"""

    HZ_20 = 0x07
    HZ_50 = 0x08
    HZ_100 = 0x09
    HZ_200 = 0x0B
    """50 Hz 以上为打包传输：一次 BLE 通知可能携带多帧，解码器已覆盖。"""


class Bandwidth(IntEnum):
    """写入 :attr:`Register.BANDWIDTH` 的传感器抗混叠滤波器带宽，七档全部登记。

    **七个标称值全部来自维特通用编码表，本库一档都没实测过。** 这与
    :class:`ReturnRate` 「每一档都在真机上实测过」不是一回事，两者的差别必须显式
    可见——此前这里写的是「只登记已核实的两档」，那句话言过其实：``ray-171`` 的验收
    清单本就记着「``BANDWIDTH`` 未逐档探测」，而证据里那句「带宽已设为 20 Hz，读回
    ``0x04``」只是把编码写进去再读回来，与截止频率是多少无关。

    **成员名在这里是转述，不是断言。** ``ReturnRate.HZ_100`` 的意思是「本库量到过
    100 Hz」，所以 ``0x0A`` 不能叫 ``HZ_125``——那会是一句假话，`docs/protocol.md`
    §6 的「测不准的不进枚举」说的就是这种断言式命名。``Bandwidth.HZ_98`` 的意思只
    是「上游表把这个编码标为 98 Hz」。转述要标明出处，但不必先实测。

    **残留风险照直说：** 读代码的人可能不看这段就把 ``HZ_98`` 当成实测值。同一张
    通用表在速率上已经被证伪过一次（``0x0A`` 标 125 Hz、实测 99.29 Hz），没有理由
    假定它在带宽上就都对。接受这个风险是一个决定（``RAY-304``）：带宽滤波上位机
    自己能做，放在下位机只是实时性更好；本库的职责是如实开放接口并标清证据强度，
    而不是替上层去核实芯片手册。要用这些数字做采样率/抗混叠的设计决策，先自己测。

    **本库真正实测到的只有两件事**（2026-08-27，一台 WT901BLE67，
    ``tools/probe_bandwidth.py``，证据 ``ray-298/bandwidth-42hz/acceptance/``，
    只覆盖 ``0x00`` / ``0x03`` / ``0x04`` 三档）：

    1. 设备接受这三个编码，写入后照常出数，30 秒采集无丢样、无重同步。
    2. 三档的截止频率**单调有序**：全频段 ``0x03`` 的衰减都严格小于 ``0x04``
       （20 Hz 处 −1.4 dB vs −7.0 dB，50 Hz 处 −2.3 dB vs −13.1 dB），而两者相对
       ``0x00`` 都是衰减。所以 ``0x00`` 最宽、``0x04`` 最窄、``0x03`` 居中。

    另四档（``0x01`` / ``0x02`` / ``0x05`` / ``0x06``）连这两件事都没测过——它们的
    证据强度**低于**上面三档，仅有的依据是上游表列出了它们。

    **数字本身没被核实，也不要假装它被核实了。** 那次取证用噪声底功率谱比值去量
    截止频率，方法带一条自校验：先拿标着 20 Hz 的 ``0x04`` 跑一遍，看能不能读回
    20 Hz。读出来是 10.9 Hz，自校验没过，所以同一次测出的 ``0x03`` = 35.6 Hz
    **同样不算数**。失败的成因有两种，那一轮分不开：要么方法无效，要么 ``0x04``
    在本型号固件上根本就不是 20 Hz。

    要推翻或坐实这些数字，需要一个动态范围足够的实验——那次实测里噪声底只有约
    20:1 的可用范围，−3 dB 拐点本就测不准。七档齐备之后，低档位（``0x05`` / ``0x06``）
    的拐点远低于出问题的区间，可以当方法的锚点用，这是三档时做不到的。

    **上游表未区分加速度与角速度两列。** MPU 类芯片的抗混叠滤波器对同一编码给两个
    略不同的截止频率（典型如加速度 44 Hz / 角速度 42 Hz），而维特那张表每个编码只
    给一个数。本库照抄该表，没有区分两列的依据——所以这些标称值即使将来被证实，也
    只能对上其中一列。

    **``0x07`` 及以上仍然拒绝。** 白名单防的是**误**写（比如 ``0x02`` 打成
    ``0x20``），这条理由与证据强度无关，与上游表对不对也无关，所以照旧。
    """

    HZ_5 = 0x06
    HZ_10 = 0x05
    HZ_20 = 0x04
    HZ_42 = 0x03
    """适配文档 §3.1 七步序列的第 ③ 步要的就是这一档。

    ``0x03`` 是本类里唯一有真机使用痕迹的编码：取证时设备 flash 里存着的就是它
    （连上读回 ``BANDWIDTH=0x03``），说明它在本型号上是个被实际用过的值。
    """

    HZ_98 = 0x02
    HZ_188 = 0x01
    HZ_256 = 0x00
