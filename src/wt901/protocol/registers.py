"""WT9011DCL-BT50 寄存器定义。

**只登记有依据的地址与取值**——凭记忆补全会写入未知语义。但「有依据」有两种来源，
且它们覆盖的范围不同，本模块此前只提了后一种：

* **协议文档** —— 维特官方《蓝牙5.0通讯协议》，本型号自己的协议文档。
* **官方 SDK** —— `WITMOTION/WitBluetooth_BWT901BLE5_0`，钉住 commit
  ``9efaab0fdd6a06dc807bf80402e58aa91b431c6f``（2024-09-19）的 C# / Android /
  Python / iOS 实现（``Form1.cs``、``Bwt901bleProcessor.java``、
  ``DipSensorMagHelper.java``）。

**这里以前写的是「来源：官方 SDK」，那句话覆盖不了本模块的一半。** SDK 全量触及的
只有读 ``0x03`` ``0x2E`` ``0x3A`` ``0x40`` ``0x51`` ``0x64`` ``0x72`` 与写 ``0x00``
``0x01`` ``0x03`` ``0x1F`` ``0x27`` ``0x69``；:attr:`Register.MOUNTING`、
:attr:`Register.ALGORITHM`、芯片时间、:attr:`Register.MAC`、
:attr:`Register.SERIAL_NUMBER`、:attr:`Register.DISPLACEMENT_OUTPUT` 这六组 SDK
一次都没碰过（2026-08-28 的全量比对，``ray-309``，逐项出处见 `docs/protocol.md` §0
与 §11）。**逐项出处现在写在各成员自己的 docstring 里**，不再有整个模块统一的来源
声明。

出处之外还有一层「证据强度」，各枚举的文档写明了自己那一档是哪种：`ReturnRate` 每档
都在真机上实测过实际速率；`Bandwidth` 七档的标称频率则**一个都没实测过**，实测过的
只有其中三档的「设备接受该编码」与「单调有序」。别把这两种混为一谈——前者的成员名是
断言，后者是对上游表的转述。
"""

